    <h1>MailDesk Privacy Policy</h1>
    <p class="muted">Last updated: 5 November 2026</p>

    <p>MailDesk is an internal customer-support tool run by 1Dollar Digitizing for its own brands
    (1Dollar Digitizing, Aplus Digitizing and Digitizing Zone). It lets our own support staff read and
    answer customer emails sent to our company Gmail accounts. It is not offered to the public.</p>

    <h2>What Google data we access</h2>
    <p>When an administrator connects one of our company Gmail accounts, MailDesk uses the Gmail API to
    read messages in the inbox, sent and spam folders, and to send replies from that same account.
    We do not access any other Google data.</p>

    <h2>How we use it</h2>
    <p>Email content is stored in our own database only so our support team can answer customers.
    Customer email addresses are hidden from support agents and visible only to administrators.
    We do not sell, share, or transfer Google user data to third parties, and we do not use it for
    advertising or to train AI models.</p>

    <h2>Limited Use</h2>
    <p>MailDesk's use and transfer of information received from Google APIs adheres to the
    <a href="https://developers.google.com/terms/api-services-user-data-policy">Google API Services User Data Policy</a>,
    including the Limited Use requirements.</p>

    <h2>Security and deletion</h2>
    <p>Data is kept on our secured server and accessed over HTTPS. An administrator can disconnect a Gmail
    account at any time, and Google access can also be revoked at
    <a href="https://myaccount.google.com/permissions">myaccount.google.com/permissions</a>.
    To have stored emails deleted, contact us.</p>

